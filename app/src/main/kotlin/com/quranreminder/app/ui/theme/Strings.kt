val LocalAppStrings = compositionLocalOf { AppStrings.uzLatin }

/** Looks up [key] in the current [LocalAppStrings], falling back to Uzbek Latin, then the key itself. */
@Composable
fun t(key: String): String {
    val strings = LocalAppStrings.current
    return strings[key] ?: AppStrings.uzLatin[key] ?: key
}
