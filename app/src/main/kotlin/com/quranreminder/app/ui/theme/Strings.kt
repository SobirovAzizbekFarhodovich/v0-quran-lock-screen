val LocalAppStrings = compositionLocalOf { AppStrings.uzLatin }

/** The locale of the app's language (not the phone's), for dates and day names. */
@Composable
fun appLocale(): java.util.Locale {
    val strings = LocalAppStrings.current
    return when (strings) {
        AppStrings.uzCyrillic -> java.util.Locale.Builder().setLanguage("uz").setScript("Cyrl").build()
        AppStrings.ru -> java.util.Locale("ru")
        AppStrings.english -> java.util.Locale.ENGLISH
        else -> java.util.Locale("uz")
    }
}

/** Looks up [key] in the current [LocalAppStrings], falling back to Uzbek Latin, then the key itself. */
@Composable
fun t(key: String): String {
    val strings = LocalAppStrings.current
    return strings[key] ?: AppStrings.uzLatin[key] ?: key
}
